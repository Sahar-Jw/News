import { DataSource } from 'typeorm';

export interface TableCol { name: string; type: string; generated: boolean; alwaysIdentity: boolean }
export interface SchemaInfo {
  /** CREATE TYPE / SEQUENCE / TABLE (+ primary keys, unique and check constraints): every statement skips what already exists */
  pre: string;
  /** foreign keys and indexes: added after the data, which is faster to load and does not depend on the order of the tables */
  post: string;
  /** columns of each table in their real order, with their types */
  columns: Map<string, TableCol[]>;
}

const q = (id: string) => `"${id.replace(/"/g, '""')}"`;
const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;

/** The structure of the given tables, read from the database catalogs (what pg_dump --schema-only would print for them, without needing pg_dump). */
export async function buildSchema(ds: DataSource, schema: string, tables: string[]): Promise<SchemaInfo> {
  const columns = new Map<string, TableCol[]>();
  if (!tables.length) return { pre: '', post: '', columns };
  const both = `JOIN pg_class c ON c.oid = %REL% JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = $1 AND c.relname = ANY($2)`;

  const cols: any[] = await ds.query(
    `SELECT c.relname AS t, a.attname AS name, format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull AS notnull,
            pg_get_expr(d.adbin, d.adrelid) AS def, a.attidentity AS ident, a.attgenerated AS gen,
            CASE WHEN pg_get_expr(d.adbin, d.adrelid) LIKE 'nextval(%' THEN pg_get_serial_sequence(format('%I.%I', n.nspname, c.relname), a.attname) END AS seq,
            (SELECT format_type(sq.seqtypid, NULL) FROM pg_sequence sq WHERE sq.seqrelid = pg_get_serial_sequence(format('%I.%I', n.nspname, c.relname), a.attname)::regclass) AS seqtype
       FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid JOIN pg_namespace n ON n.oid = c.relnamespace
       LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
      WHERE n.nspname = $1 AND c.relname = ANY($2) AND c.relkind IN ('r', 'p') AND a.attnum > 0 AND NOT a.attisdropped
      ORDER BY c.relname, a.attnum`, [schema, tables]);
  const cons: any[] = await ds.query(
    `SELECT c.relname AS t, k.conname AS name, k.contype AS kind, pg_get_constraintdef(k.oid) AS def
       FROM pg_constraint k ${both.replace('%REL%', 'k.conrelid')} AND k.contype IN ('p', 'u', 'c', 'f')
      ORDER BY c.relname, (k.contype <> 'p'), k.conname`, [schema, tables]);
  const idx: any[] = await ds.query(
    `SELECT pg_get_indexdef(i.indexrelid) AS def
       FROM pg_index i ${both.replace('%REL%', 'i.indrelid')} AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conindid = i.indexrelid)
      ORDER BY c.relname, 1`, [schema, tables]);
  const enums: any[] = await ds.query(
    `SELECT t.typname AS name, array_agg(e.enumlabel::text ORDER BY e.enumsortorder) AS labels
       FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid JOIN pg_namespace n ON n.oid = t.typnamespace
      WHERE n.nspname = $1 GROUP BY t.typname ORDER BY t.typname`, [schema]);

  const S = q(schema);
  const pre: string[] = [];
  const post: string[] = [];
  for (const e of enums) {
    pre.push(`DO $ddl$ BEGIN CREATE TYPE ${S}.${q(e.name)} AS ENUM (${(e.labels as string[]).map(lit).join(', ')}); EXCEPTION WHEN duplicate_object THEN NULL; END $ddl$;`);
  }
  const quoted = (sq: string) => sq.split('.').map((p) => (p.startsWith('"') ? p : q(p))).join('.');
  const seqs = new Map<string, string>();
  for (const c of cols) if (c.seq) seqs.set(c.seq as string, (c.seqtype as string) || 'bigint');
  for (const [sq, type] of seqs) pre.push(`CREATE SEQUENCE IF NOT EXISTS ${quoted(sq)} AS ${type};`);

  for (const t of tables) {
    const tc = cols.filter((c) => c.t === t);
    if (!tc.length) continue;
    columns.set(t, tc.map((c) => ({ name: c.name, type: c.type, generated: c.gen === 's', alwaysIdentity: c.ident === 'a' })));
    const lines = tc.map((c) => {
      let l = `  ${q(c.name)} ${c.type}`;
      if (c.gen === 's') l += ` GENERATED ALWAYS AS (${c.def}) STORED`;
      else if (c.ident === 'a') l += ' GENERATED ALWAYS AS IDENTITY';
      else if (c.ident === 'd') l += ' GENERATED BY DEFAULT AS IDENTITY';
      else if (c.def != null) l += ` DEFAULT ${c.def}`;
      if (c.notnull && c.ident === '' ) l += ' NOT NULL';
      return l;
    });
    for (const k of cons.filter((x) => x.t === t && x.kind !== 'f')) lines.push(`  CONSTRAINT ${q(k.name)} ${k.def}`);
    pre.push(`CREATE TABLE IF NOT EXISTS ${S}.${q(t)} (\n${lines.join(',\n')}\n);`);
    for (const c of tc.filter((x) => x.seq)) pre.push(`ALTER SEQUENCE ${quoted(c.seq as string)} OWNED BY ${S}.${q(t)}.${q(c.name)};`);
    for (const k of cons.filter((x) => x.t === t && x.kind === 'f')) {
      post.push(`DO $ddl$ BEGIN ALTER TABLE ${S}.${q(t)} ADD CONSTRAINT ${q(k.name)} ${k.def}; EXCEPTION WHEN duplicate_object THEN NULL; END $ddl$;`);
    }
  }
  for (const i of idx) post.push(`${(i.def as string).replace(/^CREATE (UNIQUE )?INDEX /, 'CREATE $1INDEX IF NOT EXISTS ')};`);
  return { pre: pre.join('\n\n'), post: post.join('\n'), columns };
}
